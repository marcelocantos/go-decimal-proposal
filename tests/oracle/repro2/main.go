package main

import (
	"fmt"
	"math"
	"strconv"
)

func p64(s string) decimal64 {
	d, err := strconv.ParseDecimal(s, 64)
	if err != nil {
		panic(err)
	}
	return decimal64(d)
}
func p128(s string) decimal128 {
	d, err := strconv.ParseDecimal(s, 128)
	if err != nil {
		panic(err)
	}
	return d
}
func show64(label string, d decimal64) {
	fmt.Printf("%-52s %-26s %%g=%s\n", label, strconv.FormatDecimal(decimal128(d), 'e', -1, 64), fmt.Sprintf("%g", d))
}
func show128(label string, d decimal128) {
	hi, _ := math.Decimal128bits(d)
	fmt.Printf("%-52s %-40s isInf=%v isNaN=%v hi=%#x\n", label, strconv.FormatDecimal(d, 'e', -1, 128), math.IsDecimal128Inf(d, 0), math.IsDecimal128NaN(d), hi)
}

func main() {
	fmt.Println("--- decimal64 add/sub, moderate exponents ---")
	show64("9999999999E9 + 10000000000E-4 (want 9.999999999001e18)", p64("9999999999E9")+p64("10000000000E-4"))
	show64("-85656E-5 - -9999999E8 (want 9.999998999999991e14)", p64("-85656E-5")-p64("-9999999E8"))
	show64("99999999999999E-10 - 10000000000E-4 (want -9.900000000000001e5)", p64("99999999999999E-10")-p64("10000000000E-4"))
	show64("-999999999999999E-4 + -0E-9 (want -99999999999.9999)", p64("-999999999999999E-4")+p64("-0E-9"))
	show64("1234567.89 + 0.000001 (want 1234567.890001)", p64("1234567.89")+p64("0.000001"))
	show64("1000000 + 0.0000001 (want 1000000.0000001, exact at exponent -7)", p64("1000000")+p64("0.0000001"))
	show64("123456789012.34 + 0.00001 (want 123456789012.3400)", p64("123456789012.34")+p64("0.00001"))
	show64("5000000000 + 0.00000001 (want 5000000000.000000)", p64("5000000000")+p64("0.00000001"))
	show64("5000000000.00 - 0.00000001 (want 4999999999.999999 or ...)", p64("5000000000.00")-p64("0.00000001"))

	fmt.Println("--- decimal64 division precision ---")
	show64("1 / 12345678 (want 8.100000664200054e-08)", p64("1")/p64("12345678"))
	show64("100 / 7000000 (want 0.00001428571428571429)", p64("100")/p64("7000000"))
	show64("2.50 / 123456789 (want 2.025000018427500e-08)", p64("2.50")/p64("123456789"))
	show64("1 / 70000000000000 (want 1.428571428571429e-14)", p64("1")/p64("70000000000000"))
	show64("19.99 / 3 (want 6.663333333333333)", p64("19.99")/p64("3"))
	show64("1000000 / 3 (want 333333.3333333333)", p64("1000000")/p64("3"))
	show64("1 / 3000000000000000 (want 3.333333333333333e-16)", p64("1")/p64("3000000000000000"))
	show64("7 / 9999999999999999 (want 7.000000000000001e-16)", p64("7")/p64("9999999999999999"))

	fmt.Println("--- decimal64 inexact-sum quantum (IEEE: 16-digit result) ---")
	show64("1 + 1e-20 (IEEE: 1.000000000000000)", p64("1")+p64("1e-20"))
	show64("100.00 + 1e-30 (IEEE: 100.0000000000000)", p64("100.00")+p64("1e-30"))

	fmt.Println("--- decimal128 ---")
	show128("1e20 + 1e-20 (want 1.000...e20)", p128("1e20")+p128("1e-20"))
	show128("1e19 + 1e-19 (want 1.000...e19, 39 digits span)", p128("1e19")+p128("1e-19"))
	show128("1e18 + 1e-18 (37 digits span)", p128("1e18")+p128("1e-18"))
	show128("1e17 + 1e-17 (35 digits span)", p128("1e17")+p128("1e-17"))
	show128("1e16 + 1e-16 (33 digits span)", p128("1e16")+p128("1e-16"))
	show128("123456789012345678901234.5678 + 0.00000000001", p128("123456789012345678901234.5678")+p128("0.00000000001"))
	show128("1e6144 * 10 (want +Inf)", p128("1e6144")*p128("10"))
	show128("9.999999999999999999999999999999999e6144 * 2 (want +Inf)", p128("9.999999999999999999999999999999999e6144")*p128("2"))
	show128("1e6138 / 1e-9 (want +Inf)", p128("1e6138")/p128("1e-9"))
	show128("1e6144 + 1e6144 (want 2e6144, below the maximum)", p128("1e6144")+p128("1e6144"))
	show128("1 / 12345678901234567890 (34 digits)", p128("1")/p128("12345678901234567890"))
	show128("1 / 7 (34 digits)", p128("1")/p128("7"))
	show128("99999999999999999999999999999999E1 * -61451140100153923530E-10", p128("99999999999999999999999999999999E1")*p128("-61451140100153923530E-10"))
	show128("  (want -6.145114010015392352999999999999939e42)", 0)
	show128("1.5 * 1.5 (want 2.25)", p128("1.5")*p128("1.5"))
	show128("12345678901234567.890123456789012345 * 1.1", p128("12345678901234567.890123456789012345")*p128("1.1"))
	show128("  (want 13580246791358024.67913580246791357: the 35-digit operand first ties to even, ...234)", 0)
}
