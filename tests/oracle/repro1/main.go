package main

import (
	"fmt"
	"math"
	"strconv"
)

func p64(s string) decimal64 {
	d, err := strconv.ParseDecimal(s, 64)
	if err != nil {
		panic(err)
	}
	return decimal64(d)
}
func p128(s string) decimal128 {
	d, err := strconv.ParseDecimal(s, 128)
	if err != nil {
		panic(err)
	}
	return d
}
func show64(label string, d decimal64) {
	fmt.Printf("%-48s %-28s bits=%#016x\n", label, strconv.FormatDecimal(decimal128(d), 'e', -1, 64)+"  (%g="+fmt.Sprintf("%g", d)+")", math.Decimal64bits(d))
}
func show128(label string, d decimal128) {
	hi, lo := math.Decimal128bits(d)
	fmt.Printf("%-48s %-40s hi=%#016x lo=%#016x\n", label, strconv.FormatDecimal(d, 'e', -1, 128), hi, lo)
}

func main() {
	fmt.Println("--- decimal64 multiply ---")
	show64("-98.8 * 1e31 (want -9.88e+32)", p64("-98.8")*p64("1e31"))
	show64("-98.8 * 1000000000000000e16 (want -9.88e+32)", p64("-98.8")*p64("1000000000000000e16"))
	show64("lit: decimal64(-98.8)*decimal64(1e31)", decimal64(-98.8)*decimal64(1e31))
	show64("99999999999999E-381 * 99999999999E367 (~1e11)", p64("99999999999999E-381")*p64("99999999999E367"))
	show64("12.5 * 8 (want 100.0)", p64("12.5")*p64("8"))
	show64("1234567890123456 * 10 (want 1.234567890123456e16)", p64("1234567890123456")*p64("10"))
	show64("9999999999999999 * 1000 (want 9.999999999999999e18, exact)", p64("9999999999999999")*p64("1000"))

	fmt.Println("--- decimal64 add/sub with exponent gap ---")
	show64("1 + 1e-20 (want 1.000000000000000)", p64("1")+p64("1e-20"))
	show64("1e20 + 1e-20", p64("1e20")+p64("1e-20"))
	show64("9999999999999999e7 - 811.2856 (want -...e7)", p64("-9999999999999999e7")-p64("811.2856"))
	show64("1234567890123456 + 0.00001", p64("1234567890123456")+p64("0.00001"))
	show64("1234567890123456 + 0.0001", p64("1234567890123456")+p64("0.0001"))
	show64("1234567890123456 + 0.001", p64("1234567890123456")+p64("0.001"))
	show64("1234567890123456 + 0.01", p64("1234567890123456")+p64("0.01"))
	show64("1234567890123456 + 0.1", p64("1234567890123456")+p64("0.1"))
	show64("100000000000000.0 - 1e21 (want -9.999999999999999e20)", p64("100000000000000e-9")-p64("100e19"))
	show64("1 + 1e-300", p64("1")+p64("1e-300"))
	z := p64("1e-382") - p64("1e-382")
	show64("zero with exp -382", z)
	show64("-999999999e39 + 0E-382 (want -9.99999999e47)", p64("-999999999e39")+z)
	show64("123.45 + 0E-382", p64("123.45")+z)
	show64("0.1 + 0.2 (sanity)", p64("0.1")+p64("0.2"))

	fmt.Println("--- decimal64 divide ---")
	show64("1000e12 / -97915621542e19 (want -1.021287496572811e-15)", p64("1000e12")/p64("-97915621542e19"))
	show64("1 / 7e10 (want 1.428571428571429e-11)", p64("1")/p64("7e10"))
	show64("1 / 3", p64("1")/p64("3"))
	show64("2 / 3", p64("2")/p64("3"))
	show64("1 / 70000000000000 (want 1.428571428571429e-14)", p64("1")/p64("70000000000000"))
	show64("935204295481E366 / 731879248134308E357", p64("935204295481E366")/p64("731879248134308E357"))
	show64("9999990 / -0.100000 (want -9.99999e7, exp 2)", p64("999999e1")/p64("-100000e-6"))
	show64("100 / 8 (want 12.5)", p64("100")/p64("8"))
	show64("1.00 / 4 (want 0.25)", p64("1.00")/p64("4"))

	fmt.Println("--- decimal128 ---")
	show128("999999999999999999999999999E8 + 6118384908704389844375805015E-14", p128("999999999999999999999999999E8")+p128("6118384908704389844375805015E-14"))
	show128("  (want 1.000000000000000000000611837490870e35)", 0)
	show128("79370027447169958363511204E14 * -99999999999999999999999999E9", p128("79370027447169958363511204E14")*p128("-99999999999999999999999999E9"))
	show128("  (want -7.937002744716995836351120320629973e74)", 0)
	show128("1e6138 / 1e-9 (want +Inf)", p128("1e6138")/p128("1e-9"))
	show128("1e6144 * 10 (want +Inf)", p128("1e6144")*p128("10"))
	show128("12345678901234567890123456789012.34 + 0.001", p128("12345678901234567890123456789012.34")+p128("0.001"))
	show128("1e20 + 1e-20 (34 digits: 1.000000000000000000000000000000000e20)", p128("1e20")+p128("1e-20"))
	show128("1/3", p128("1")/p128("3"))
	show128("234978520688775E-17 / 9047123382365178798256528742811E-4801", p128("234978520688775E-17")/p128("9047123382365178798256528742811E-4801"))
	show128("  (want 2.597273307301185964404701320706016e4767)", 0)
}
