// The conversions between decimal values and text are those of
// internal/bid: parseDecimal reads its input with bid.Parse64 or bid.Parse128,
// and formatDecimal and appendDecimal take
// the coefficient digits, sign and quantum from bid.UnpackDigits128. This
// file owns the format verbs and precision, and the layout of the digits
// that follows from them. Whenever a precision asks for fewer digits than
// a value has, the value is rounded by the kernel's Quantize.

// formatDecimal converts a decimal128 value to a string.
// The format fmt and precision prec follow the same rules as [FormatFloat],
// except for the special precision -1. For a binary float that means the
// fewest digits that round-trip the value. A decimal value also has a quantum,
// so it means all the digits of the coefficient: 1.50 formats as "1.50", and
// [parseDecimal] of that string returns the same value and quantum.
//
// With 'g' and 'G' and the special precision -1, the result is the canonical
// string. It is in fixed notation unless the exponent of the leading digit is
// less than -6 or at least 21, or the quantum is above the units digit, which
// fixed notation can't show: 1e+03 is not 1000.
//
// The bitSize must be 64 for values from decimal64 or 128 for decimal128.
//
//go:linkname formatDecimal
func formatDecimal(d decimal128, fmt byte, prec int, bitSize int) string {
	// The canonical form fits on the stack. Explicit fixed-point formats
	// and large precisions may grow past this buffer through append.
	var buf [bid.MaxLen128]byte
	return string(appendDecimal(buf[:0], d, fmt, prec, bitSize))
}

// appendDecimal appends the string form of the decimal128 value d,
// as generated by formatDecimal, to dst and returns the extended buffer.
// The bitSize must be 64 for values widened from decimal64 or 128 for decimal128.
//
//go:linkname appendDecimal
func appendDecimal(dst []byte, d decimal128, fmt byte, prec int, bitSize int) []byte {
	// A decimal64 widens exactly, with the same coefficient and exponent,
	// so both widths have the same digits and the same rounding.
	_ = bitSize

	hi, lo := decimal.BID128bits(d)
	x := bid.Uint128{Hi: hi, Lo: lo}

	var digs [bid.Precision128]byte
	kind, neg, n, exp := bid.UnpackDigits128(&digs, x)
	switch kind {
	case bid.KindNaN:
		return append(dst, "NaN"...)
	case bid.KindInf:
		if neg {
			return append(dst, "-Inf"...)
		}
		return append(dst, "+Inf"...)
	}

	if prec < 0 {
		// Canonical output keeps all coefficient digits and the quantum. Keep
		// its layout here so it needs neither a call nor the rounding state.
		format := normalFormat(fmt)
		digits := digs[len(digs)-n:]
		if n == 0 {
			digits = []byte{'0'}
		}
		if neg {
			dst = append(dst, '-')
		}
		switch format {
		case 'e', 'E':
			return appendExp(dst, digits, exp, format, -1)
		case 'f':
			if n == 0 {
				exp = min(exp, 0)
			}
			return appendFixed(dst, digits, exp, -1)
		}
		e := exp + len(digits) - 1
		if e < canonicalMinExp || e >= canonicalMaxExp || exp > 0 {
			ef := byte('e')
			if format == 'G' {
				ef = 'E'
			}
			return appendExp(dst, digits, exp, ef, -1)
		}
		if exp == 0 {
			return append(dst, digits...)
		}
		// The canonical fixed form neither rounds nor pads when the point is
		// inside the coefficient. Reserve the whole result once, then place
		// the two digit spans without the general formatter's append checks.
		point := len(digits) + exp
		if point > 0 && cap(dst)-len(dst) >= len(digits)+1 {
			start := len(dst)
			dst = dst[:start+len(digits)+1]
			for i := 0; i < point; i++ {
				dst[start+i] = digits[i]
			}
			dst[start+point] = '.'
			for i := point; i < len(digits); i++ {
				dst[start+i+1] = digits[i]
			}
			return dst
		}
		return appendFixed(dst, digits, exp, -1)
	}
	v := finite{neg: neg, n: n, exp: exp, digs: &digs}
	if v.n > 0 {
		v.round(x, normalFormat(fmt), prec)
	}
	if v.n == 0 {
		return appendZero(dst, v.neg, fmt, prec)
	}
	return formatDigits(dst, v.neg, v.exp, v.digs[len(v.digs)-v.n:], normalFormat(fmt), prec)
}

// parseDecimal converts a string to a decimal value of the given bitSize, 64 or
// 128, rounded to nearest even from the exact value the string denotes. The
// result has type decimal128 whatever the bitSize, as [ParseFloat]'s result has
// type float64; it converts to decimal64 without changing its value or quantum
// if bitSize is 64.
//
// The string is a decimal numeral (an optional sign, digits with an optional
// point, and an optional exponent) or one of the words "inf", "infinity",
// "nan" and "snan", with an optional sign and in any case. Nothing else is
// accepted: no surrounding space, no underscores, no hexadecimal form, and
// no characters after a word. The quantum of the result is that of the numeral
// if the value is exact.
//
// If s is not syntactically well-formed, parseDecimal returns zero and
// err.Err = ErrSyntax. If s is well-formed but rounds to a magnitude beyond the
// largest value of the size, parseDecimal returns ±Inf and err.Err = ErrRange.
// As with [ParseFloat], a value too small for the format is not an error:
// it rounds to a subnormal value or to zero.
//
//go:linkname parseDecimal
func parseDecimal(s string, bitSize int) (decimal128, error) {
	var d decimal128
	var st bid.Status
	if bitSize == 64 {
		var x uint64
		x, st = bid.Parse64(s, bid.ToNearestEven)
		d = decimal128(decimal.BID64frombits(x))
	} else {
		var x bid.Uint128
		x, st = bid.Parse128(s, bid.ToNearestEven)
		d = decimal.BID128frombits(x.Hi, x.Lo)
	}
	if st&bid.Syntax != 0 {
		return 0, syntaxError("ParseDecimal", s)
	}
	if st&bid.Overflow != 0 {
		return d, rangeError("ParseDecimal", s)
	}
	return d, nil
}

// --- Coefficient digits ---

// A finite holds the coefficient digits of a finite value: the value
// is (-1)^neg × digs[len(digs)-n:] × 10^exp. There are no leading zeros;
// n is zero for a zero value, whatever its exponent.
type finite struct {
	neg  bool
	n    int
	exp  int
	digs *[bid.Precision128]byte
}

// round rounds the value to the precision that format and prec call for:
// prec+1 significant digits for 'e', prec significant digits for 'g' (one
// if prec is zero) and prec places after the point for 'f'. It does nothing
// if the value has no more digits than that. The rounding is the kernel's
// Quantize to nearest even; x is the encoding of the value.
func (v *finite) round(x bid.Uint128, format byte, prec int) {
	var keep int // significant digits to keep, or -1 for none in particular
	var exp int  // the exponent of the least significant digit kept
	switch format {
	case 'e', 'E':
		keep = prec + 1
		exp = v.exp + v.n - keep
	case 'g', 'G':
		keep = max(prec, 1)
		exp = v.exp + v.n - keep
	default: // 'f'
		keep = -1
		exp = -prec
	}
	drop := exp - v.exp // digits to discard
	if drop <= 0 {
		return
	}
	if drop > v.n {
		// The value is below a tenth of the last place kept.
		v.n = 0
		return
	}

	// Quantize works on the encoding. The value has the exponent v.exp,
	// which may put the quantum out of the format's range (the exponent of
	// a decimal with 34 digits is 6111 at most; the quantum may be 6144),
	// so quantize the coefficient alone, at exponent zero, and put the
	// exponent back afterwards.
	_, neg, coeff, _ := bid.Unpack128(x)
	c, _ := bid.Pack128(neg, coeff, 0)
	quantum, _ := bid.Pack128(false, bid.Uint128{Lo: 1}, drop)
	q := bid.Quantize128(c, quantum, bid.ToNearestEven)

	_, _, n, qexp := bid.UnpackDigits128(v.digs, q)
	v.n = n
	v.exp += qexp
	if keep > 0 && v.n > keep {
		// A carry made 9.99 into 10.0. The extra digit is a zero.
		// Keep the leading digits right-aligned after dropping that zero.
		copy(v.digs[len(v.digs)-keep:], v.digs[len(v.digs)-v.n:len(v.digs)-v.n+keep])
		v.exp += v.n - keep
		v.n = keep
	}
}

// --- Layout ---

// normalFormat is the verb that formatDigits lays out for fmt: unknown
// verbs are 'g'.
func normalFormat(fmt byte) byte {
	switch fmt {
	case 'e', 'E', 'f', 'g', 'G':
		return fmt
	}
	return 'g'
}

// appendZero appends a zero of the given sign.
func appendZero(dst []byte, neg bool, format byte, prec int) []byte {
	if neg {
		dst = append(dst, '-')
	}
	switch format {
	case 'e', 'E':
		if prec <= 0 {
			dst = append(dst, '0', format)
			return append(dst, "+00"...)
		}
		dst = append(dst, "0."...)
		for i := 0; i < prec; i++ {
			dst = append(dst, '0')
		}
		dst = append(dst, format)
		return append(dst, "+00"...)
	case 'g', 'G':
		// %g strips trailing zeros, so zero is always "0".
		// The fmt layer's # flag restores trailing zeros if needed.
		return append(dst, '0')
	default: // 'f'
		if prec <= 0 {
			return append(dst, '0')
		}
		dst = append(dst, "0."...)
		for i := 0; i < prec; i++ {
			dst = append(dst, '0')
		}
		return dst
	}
}

// Exponents of the leading digit outside this range use exponent notation in
// the canonical string. They are the thresholds encoding/json uses for floats.
const (
	canonicalMinExp = -6
	canonicalMaxExp = 21
)

// formatDigits formats the non-zero value (-1)^neg × digits × 10^exp, where
// format is one of 'e', 'E', 'f', 'g' and 'G' and prec is not negative. The
// digits are already rounded to prec.
func formatDigits(dst []byte, neg bool, exp int, digits []byte, format byte, prec int) []byte {
	ndigits := len(digits)

	if neg {
		dst = append(dst, '-')
	}

	switch format {
	case 'e', 'E':
		return appendExp(dst, digits, exp, format, prec)
	case 'f':
		return appendFixed(dst, digits, exp, prec)
	}

	// 'g' uses 'e' for large/small exponents, 'f' otherwise.
	// Trailing zeros and trailing decimal points are stripped.
	ef := byte('e')
	if format == 'G' {
		ef = 'E'
	}
	e := exp + ndigits - 1
	p := max(prec, 1)
	if e >= -4 && e < p {
		return stripTrailingZeros(appendFixed(dst, digits, exp, p-ndigits-exp))
	}
	return stripTrailingZeros(appendExp(dst, digits, exp, ef, p-1))
}

// appendFixed formats in fixed-point notation. If prec is not negative the
// digits have at most prec places after the point; fewer are padded with
// zeros.
func appendFixed(dst []byte, digits []byte, exp int, prec int) []byte {
	ndigits := len(digits)
	// intPart = ndigits + exp (digits before the decimal point)
	intPart := ndigits + exp

	if intPart <= 0 {
		// 0.000...digits
		dst = append(dst, '0')
		if prec != 0 && (prec < 0 && ndigits > 0 || prec > 0) {
			dst = append(dst, '.')
			leading := -intPart
			for i := 0; i < leading; i++ {
				dst = append(dst, '0')
			}
			dst = append(dst, digits...)
			if prec > 0 {
				written := leading + ndigits
				for written < prec {
					dst = append(dst, '0')
					written++
				}
			}
		}
	} else if intPart >= ndigits {
		// All digits are before the decimal point.
		dst = append(dst, digits...)
		for i := ndigits; i < intPart; i++ {
			dst = append(dst, '0')
		}
		if prec > 0 {
			dst = append(dst, '.')
			for i := 0; i < prec; i++ {
				dst = append(dst, '0')
			}
		}
	} else {
		// Decimal point within digits.
		dst = append(dst, digits[:intPart]...)
		if prec != 0 {
			dst = append(dst, '.')
			dst = append(dst, digits[intPart:]...)
			if prec > 0 {
				written := ndigits - intPart
				for written < prec {
					dst = append(dst, '0')
					written++
				}
			}
		}
	}
	return dst
}

// appendExp formats in scientific notation. If prec is not negative the
// digits are at most prec+1; fewer are padded with zeros.
func appendExp(dst []byte, digits []byte, exp int, format byte, prec int) []byte {
	ndigits := len(digits)

	// Value is digits[0].digits[1:] × 10^e  where e = exp + ndigits - 1
	e := exp + ndigits - 1

	dst = append(dst, digits[0])
	fracDigits := ndigits - 1
	if prec > 0 || (prec < 0 && fracDigits > 0) {
		dst = append(dst, '.')
		dst = append(dst, digits[1:1+fracDigits]...)
		// Pad with zeros if needed.
		if prec > 0 {
			for i := fracDigits; i < prec; i++ {
				dst = append(dst, '0')
			}
		}
	}

	dst = append(dst, format)
	if e < 0 {
		dst = append(dst, '-')
		e = -e
	} else {
		dst = append(dst, '+')
	}
	// BID128 exponents can reach ~6176, requiring up to 4 digits.
	if e >= 1000 {
		dst = append(dst, byte(e/1000)+'0')
	}
	if e >= 100 {
		dst = append(dst, byte(e/100%10)+'0')
	}
	if e >= 10 {
		dst = append(dst, byte(e/10%10)+'0')
	} else {
		dst = append(dst, '0')
	}
	dst = append(dst, byte(e%10)+'0')
	return dst
}

// stripTrailingZeros removes trailing zeros after a decimal point,
// and the decimal point itself if no fractional digits remain.
// It handles scientific notation (e.g., "1.230e+02" → "1.23e+02").
func stripTrailingZeros(dst []byte) []byte {
	// Find the exponent part if present.
	expIdx := -1
	for i := len(dst) - 1; i >= 0; i-- {
		if dst[i] == 'e' || dst[i] == 'E' {
			expIdx = i
			break
		}
	}

	// Find decimal point.
	dotIdx := -1
	end := len(dst)
	if expIdx >= 0 {
		end = expIdx
	}
	for i := 0; i < end; i++ {
		if dst[i] == '.' {
			dotIdx = i
			break
		}
	}
	if dotIdx < 0 {
		return dst // no decimal point, nothing to strip
	}

	// Strip trailing zeros from fractional part (before exponent if present).
	stripTo := end
	for stripTo > dotIdx+1 && dst[stripTo-1] == '0' {
		stripTo--
	}
	// Remove decimal point if no fractional digits remain.
	if stripTo == dotIdx+1 {
		stripTo = dotIdx
	}

	if stripTo == end {
		return dst // nothing stripped
	}

	// Rebuild: dst[:stripTo] + dst[expIdx:]
	if expIdx >= 0 {
		tail := append([]byte(nil), dst[expIdx:]...)
		dst = append(dst[:stripTo], tail...)
	} else {
		dst = dst[:stripTo]
	}
	return dst
}
